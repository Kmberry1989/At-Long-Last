// pickActivityPrompt-compatible helper: returns all prompts for an activity,
// favouring unseen prompts when a history Set of seen prompt strings is given.
export function getActivityPrompts(activityId, seenPrompts = new Set()) {
  const act = getExpandedActivity(activityId);
  if (!act) return [];
  const unseen = act.prompts.filter((p) => !seenPrompts.has(p));
  return unseen.length > 0 ? unseen : act.prompts;
}
export function pickActivityPrompt(activityId, seenPrompts = new Set()) {
  const pool = getActivityPrompts(activityId, seenPrompts);
  if (pool.length === 0) return null;
  return pool[Math.floor(Math.random() * pool.length)];
}
