const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH || `${process.env.HOME}/.codex/skills/develop-web-game/scripts/node_modules/playwright/index.mjs`)
import { readFile, writeFile } from 'node:fs/promises'
const out='.playwright-mcp/independent-night', base=process.env.QA_BASE_URL || 'http://127.0.0.1:5173'
const people=JSON.parse(await readFile(`${out}/people.json`,'utf8'))
const browser=await chromium.launch({channel:'chrome',headless:true})
const errors=[]
const page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,reducedMotion:'no-preference'})
page.on('pageerror',error=>errors.push(error.message))
try {
  await page.goto(base)
  await page.getByRole('button',{name:'Sign in',exact:true}).waitFor()
  await page.evaluate(()=>document.fonts.ready)
  const sky=page.locator('.auth-screen .login-sky')
  if(await sky.evaluate(node=>getComputedStyle(node).display)==='none')throw new Error('Login sky missing')
  await page.locator('.shooting-star').first().evaluate(node=>node.getAnimations()[0].currentTime=7800)
  await page.screenshot({path:`${out}/login-shooting-star.png`,fullPage:true})
  await page.emulateMedia({reducedMotion:'reduce'})
  if(await sky.evaluate(node=>getComputedStyle(node).display)!=='none')throw new Error('Reduced motion did not stop stars')
  await page.getByLabel('Email',{exact:true}).fill(people[1].email)
  await page.getByLabel('Password',{exact:true}).fill(people[1].password)
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await page.getByRole('button',{name:'Scrapbook',exact:true}).click()
  await page.getByRole('img',{name:"Avery's drawing"}).waitFor()
  await page.getByRole('img',{name:"Rowan's drawing"}).waitFor()
  await page.locator('.scrapbook-wavelength-scorecard').waitFor()
  const scorecard=await page.locator('.scrapbook-wavelength-scorecard').innerText()
  if(!scorecard.includes('Avery said')||!scorecard.includes('Rowan said'))throw new Error('Missing full comparison')
  await page.getByRole('img',{name:"Rowan's drawing"}).scrollIntoViewIfNeeded()
  await page.screenshot({path:`${out}/both-portraits-reveal.png`,fullPage:true})
  await page.locator('.scrapbook-wavelength-scorecard').scrollIntoViewIfNeeded()
  await page.screenshot({path:`${out}/prediction-scorecard.png`,fullPage:true})
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw new Error('Mobile overflow')
  await page.getByRole('button',{name:'Scrapbook',exact:true}).click()
  await page.emulateMedia({reducedMotion:'no-preference'})
  const button=page.getByRole('button',{name:'Quick',exact:true})
  await button.scrollIntoViewIfNeeded()
  await page.waitForTimeout(400)
  const box=await button.boundingBox(), client=await page.context().newCDPSession(page)
  await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:box.x+box.width/2,y:box.y+box.height/2,id:1,radiusX:5,radiusY:5,force:.6}]})
  await page.waitForTimeout(100)
  console.log('touch target', await page.evaluate(({x,y})=>document.elementFromPoint(x,y)?.outerHTML.slice(0,180),{x:box.x+box.width/2,y:box.y+box.height/2}))
  const pressed=await button.evaluate(node=>getComputedStyle(node).scale)
  if(!Number.isFinite(Number(pressed)) || Number(pressed)>=1)throw new Error('Touch press did not animate')
  await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  await page.waitForTimeout(350)
  const released=await button.evaluate(node=>getComputedStyle(node).scale)
  console.log('touch scales', {pressed,released,held:await button.getAttribute('data-pressed')})
  await page.waitForFunction(() => { const button=[...document.querySelectorAll('button')].find(node=>node.textContent.trim()==='Quick'); const scale=getComputedStyle(button).scale; return !button.hasAttribute('data-pressed') && (scale==='none'||Math.abs(Number(scale)-1)<.002) })
  await page.setViewportSize({width:1440,height:900})
  await page.screenshot({path:`${out}/desktop-home.png`,fullPage:true})
  // Reproduce the production-reset lifecycle only against the throwaway emulator user.
  await fetch(`http://127.0.0.1:8080/v1/projects/demo-pacing-local/databases/(default)/documents/profiles/${people[1].uid}`,{method:'DELETE',headers:{authorization:'Bearer owner'}})
  const deleted=await fetch('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:delete?key=demo-key',{method:'POST',headers:{authorization:'Bearer owner','content-type':'application/json'},body:JSON.stringify({localId:people[1].uid})})
  if(!deleted.ok)throw new Error(await deleted.text())
  await page.reload()
  await page.getByRole('button',{name:'Sign in',exact:true}).waitFor()
  const profile=await fetch(`http://127.0.0.1:8080/v1/projects/demo-pacing-local/databases/(default)/documents/profiles/${people[1].uid}`,{headers:{authorization:'Bearer owner'}})
  if(profile.status!==404)throw new Error('Deleted account recreated its profile')
  const evidence={shootingStar:true,reducedMotion:true,bothDrawings:true,fullScorecard:true,touchPressedScale:pressed,touchReleasedScale:released,deletedAccountReturnsToSignIn:true,errors}
  if(errors.length)throw new Error(JSON.stringify(errors))
  await writeFile(`${out}/presentation-evidence.json`,JSON.stringify(evidence,null,2))
  console.log(evidence)
}finally{await browser.close()}
